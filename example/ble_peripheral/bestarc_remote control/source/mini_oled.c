/* ══════════ Framebuffer 操作 ═══════════════════ */
void oled_set_pixel(uint8_t x, uint8_t y, uint8_t on)
{
    if(x>=OLED_WIDTH||y>=OLED_HEIGHT)return;
    uint16_t idx = x + (y/8u)*OLED_WIDTH;
    if(on) s_fb[idx] |=  (1u << (y%8u));
    else   s_fb[idx] &= ~(1u << (y%8u));
}

/* 把 FB 推到 SSD1306 (page mode write) */
void oled_flush(void)
{
    uint8_t page;
    for(page=0; page<OLED_PAGES; page++){
        _cmd2(0xB0|page, 0x00);     /* page + col lo */
        _cmd(0x10);                  /* col hi */
        _i2c_start();
        _i2c_send(0x40);            /* data mode */
        _i2c_send_buf(&s_fb[page*OLED_WIDTH], OLED_WIDTH);
    }
}

void oled_clear(void)
{
    memset(s_fb, 0, sizeof(s_fb));
}

/* ══════════ 字符/字符串 绘制 ═══════════════════ */
void oled_draw_char(uint8_t x, uint8_t y, char c)
{
    uint8_t i, j, idx;
    if(c<32||c>127) c=' ';
    idx = (uint8_t)c - 32;
    for(i=0; i<OLED_FONT_W; i++){
        uint8_t col = s_font[idx][i];
        for(j=0; j<OLED_FONT_H; j++){
            oled_set_pixel(x+i, y+j, (col>>j)&1);
        }
    }
}

void oled_draw_str(uint8_t x, uint8_t y, const char* str)
{
    while(*str){
        oled_draw_char(x,y,*str++);
        x+=OLED_FONT_W;
    }
}

/* ══════════ 初始化 ═════════════════════════════ */
void oled_init(void)
{
    uint8_t i;

    /* I2C */
    hal_gpio_pin_init(OLED_PIN_SDA, GPIO_INPUT);
    hal_gpio_pin_init(OLED_PIN_SCL, GPIO_INPUT);
    hal_gpio_pull_set(OLED_PIN_SDA, STRONG_PULL_UP);
    hal_gpio_pull_set(OLED_PIN_SCL, STRONG_PULL_UP);
    hal_i2c_pin_init(OLED_I2C_DEV, OLED_PIN_SDA, OLED_PIN_SCL);
    hal_i2c_init(OLED_I2C_DEV, I2C_CLOCK_400K);

    /* SSD1306 init sequence — 每个字节作为命令逐个发送 */
    for(i=0; i<sizeof(s_init_seq); i++){
        _cmd(s_init_seq[i]);
    }
    oled_clear();
    oled_flush();
    s_ready = 1;
    LOG("[OLED] SSD1306 128x64 ready (mini driver)\n");
}

uint8_t oled_ready(void) { return s_ready; }

/* ══════════ 滚动动画 "happy birthday" ══════════ */
void oled_scroll_task(void)
{
    if(!s_ready)return;
    oled_clear();

    /* "happy birthday" = 14 chars × 6px = 84px wide
       屏幕 128px, 从右到左滚动, 每帧 2px */
    s_scroll_x -= 2;
    if(s_scroll_x < -84) s_scroll_x = 128;

    oled_draw_str((uint8_t)s_scroll_x, 28, "happy birthday");
    oled_flush();
}
