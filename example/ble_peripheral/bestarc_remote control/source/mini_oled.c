#define OLED_WIDTH       128u
#define OLED_HEIGHT      64u
#define OLED_PAGES       8u
#define OLED_FONT_W      6u
#define OLED_FONT_H      8u

static uint8_t s_fb[OLED_WIDTH * OLED_PAGES];  /* 1024B */
