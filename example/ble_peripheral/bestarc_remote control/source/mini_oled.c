/* ══════════ I2C =═════════════════════════════════ */
static void _i2c_start(void)
{
    hal_i2c_addr_update(AP_I2C1, OLED_ADDR);
    hal_i2c_tx_start(AP_I2C1);
}
static void _i2c_send(uint8_t d)
{
    hal_i2c_send(AP_I2C1, &d, 1);
}
static void _i2c_send_buf(const uint8_t* p, uint8_t n)
{
    hal_i2c_send(AP_I2C1, (uint8_t*)p, n);
}

/* ══════════ SSD1306 命令 ════════════════════════ */
static void _cmd(uint8_t b)
{
    _i2c_start(); _i2c_send(0x00); _i2c_send(b);
}
static void _cmd2(uint8_t a, uint8_t b)
{
    _i2c_start(); _i2c_send(0x00); _i2c_send(a); _i2c_send(b);
}

static const uint8_t s_init_seq[] = {
    0xAE,       /* display off */
    0xD5,0x80, /* clock div */
    0xA8,0x3F, /* mux = 64 */
    0xD3,0x00, /* offset = 0 */
    0x40,       /* start line */
    0x8D,0x14, /* charge pump on */
    0x20,0x00, /* horizontal addressing */
    0xA1,       /* seg remap */
    0xC8,       /* com scan direction */
    0xDA,0x12, /* com pins */
    0x81,0xCF, /* contrast */
    0xD9,0xF1, /* pre-charge */
    0xDB,0x40, /* VCOMH */
    0xA4,       /* display on resume */
    0xA6,       /* normal (not inverse) */
    0xAF,       /* display on */
};

